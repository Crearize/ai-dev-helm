'use strict';

// 3.7.0 (C3j): the manifest's `workflow` ({ remote, issues, protectedBranches }) and `apps` ({ frontend, backend }).
// protectedBranches (default main and master) extends the force-push denials of .claude/settings.json and the Codex
// safety rules to the product's other protected branches (platform: release). apps places the stack rules' Cursor
// globs where the product keeps its apps (Kakaseru, OlbaDataMatching, MasterPlan).

const fs = require('fs');
const path = require('path');

const BUILT_IN = ['main', 'master'];
const BRANCH_RE = /^[A-Za-z0-9._/-]+$/;
const APP_RE = /^[A-Za-z0-9._/-]+$/;

/** Protected branches beyond main / master (validated names only). */
function extraBranches(workflow) {
  const list = workflow && Array.isArray(workflow.protectedBranches) ? workflow.protectedBranches : [];
  return [...new Set(list.filter((b) => typeof b === 'string' && BRANCH_RE.test(b) && !b.startsWith('-') && !BUILT_IN.includes(b)))];
}

// 3.7.1 (D2): the delete forms too (the quality gate refuses them as well, with or without a flag).
const denyEntries = (branches) => branches.flatMap((b) => [
  `Bash(git push --force origin ${b})`, `Bash(git push --force-with-lease origin ${b})`, `Bash(git push -f origin ${b})`,
  `Bash(git push origin :${b})`, `Bash(git push origin --delete ${b})`, `Bash(git push --delete origin ${b})`,
]);

/** Add the force-push denials of the extra protected branches to a settings.json (union, sorted). */
function addProtectedDenies(settingsPath, workflow) {
  const extra = denyEntries(extraBranches(workflow));
  if (!extra.length || !fs.existsSync(settingsPath)) return false;
  let json;
  try { json = JSON.parse(fs.readFileSync(settingsPath, 'utf8')); } catch { return false; }
  if (!json || typeof json !== 'object') return false;
  if (!json.permissions || typeof json.permissions !== 'object' || Array.isArray(json.permissions)) json.permissions = {};
  const deny = new Set(Array.isArray(json.permissions.deny) ? json.permissions.deny : []);
  const before = deny.size;
  for (const entry of extra) deny.add(entry);
  if (deny.size === before) return false;
  json.permissions.deny = [...deny].sort();
  fs.writeFileSync(settingsPath, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
  return true;
}

const CODEX_RULES_FILE = 'ai-dev-helm-protected.rules';

/** The Codex safety rules for the extra protected branches (null when there are none). */
function codexProtectedRules(workflow) {
  const branches = extraBranches(workflow);
  if (!branches.length) return null;
  const list = (prefix = '') => `[${branches.flatMap((b) => [`"${prefix}${b}"`, `"${prefix}HEAD:${b}"`]).join(', ')}]`;
  const why = 'justification = "Force pushing a protected branch rewrites shared history."';
  const names = `[${branches.map((b) => `"${b}"`).join(', ')}]`;
  const del = 'justification = "Deleting a protected branch removes shared history."';
  return [
    '# Generated by ai-dev-helm from .ai-dev-helm.json workflow.protectedBranches (beyond main / master).',
    `prefix_rule(pattern = ["git", "push", ["--force", "--force-with-lease", "-f"], "origin", ${list()}], decision = "forbidden", ${why})`,
    `prefix_rule(pattern = ["git", "push", "origin", ["--force", "--force-with-lease", "-f"], ${list()}], decision = "forbidden", ${why})`,
    `prefix_rule(pattern = ["git", "push", "origin", ${list()}, ["--force", "--force-with-lease", "-f"]], decision = "forbidden", ${why})`,
    `prefix_rule(pattern = ["git", "push", "origin", ${list('+')}], decision = "forbidden", ${why})`,
    // 3.7.1 (D2): the delete forms.
    `prefix_rule(pattern = ["git", "push", "origin", [${branches.map((b) => `":${b}"`).join(', ')}]], decision = "forbidden", ${del})`,
    `prefix_rule(pattern = ["git", "push", "origin", "--delete", ${names}], decision = "forbidden", ${del})`,
    `prefix_rule(pattern = ["git", "push", "--delete", "origin", ${names}], decision = "forbidden", ${del})`,
    '',
  ].join('\n');
}

function writeCodexProtectedRules(projectDir, workflow) {
  const text = codexProtectedRules(workflow);
  if (!text) return false;
  const file = path.join(projectDir, '.codex', 'rules', CODEX_RULES_FILE);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text, 'utf8');
  return true;
}

/** A relative directory inside the product (POSIX, no ".."), normalized; null when it is not one. */
function cleanAppDir(value) {
  if (typeof value !== 'string') return null;
  const dir = value.replace(/\\/g, '/').replace(/^\.\//, '').replace(/\/+$/, '');
  return dir && APP_RE.test(dir) && !dir.startsWith('/') && !dir.split('/').some((p) => p === '..' || p === '.' || p === '') ? dir : null;
}

/** The app directory for a rules group ('frontend' / 'backend'), from apps or the default name. */
function appDir(apps, group) {
  return (apps && cleanAppDir(apps[group])) || group;
}

/**
 * 3.7.0 (C3g): `settings.enabledPlugins` ({ "<plugin>@<marketplace>": true | false }) is written into
 * .claude/settings.json - e.g. turning the external superpowers plugin off where the skills are copied in
 * (auFinancialPromotions). Only the declared keys are set; the product's other plugins are kept.
 */
function applyEnabledPlugins(settingsPath, settings) {
  const declared = settings && settings.enabledPlugins;
  if (!declared || typeof declared !== 'object' || Array.isArray(declared) || !fs.existsSync(settingsPath)) return false;
  let json;
  try { json = JSON.parse(fs.readFileSync(settingsPath, 'utf8')); } catch { return false; }
  if (!json || typeof json !== 'object') return false;
  const current = json.enabledPlugins && typeof json.enabledPlugins === 'object' && !Array.isArray(json.enabledPlugins) ? json.enabledPlugins : {};
  const entries = Object.entries(declared).filter(([, v]) => typeof v === 'boolean');
  if (entries.every(([k, v]) => current[k] === v)) return false;
  json.enabledPlugins = { ...current, ...Object.fromEntries(entries) };
  fs.writeFileSync(settingsPath, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
  return true;
}

// The manifest-only keys `init --config` takes and `upgrade` renders with.
const EXTRA_KEYS = ['workflow', 'apps', 'settings'];

function extrasOf(obj) {
  const out = {};
  if (!obj || typeof obj !== 'object') return out;
  for (const key of EXTRA_KEYS) if (obj[key] && typeof obj[key] === 'object' && !Array.isArray(obj[key])) out[key] = obj[key];
  return out;
}

/** Shape errors of workflow / apps / settings in a manifest (or an init --config object). */
function extrasErrors(obj) {
  const errors = [];
  if (!obj || typeof obj !== 'object') return errors;
  for (const key of EXTRA_KEYS) {
    if (obj[key] !== undefined && (!obj[key] || typeof obj[key] !== 'object' || Array.isArray(obj[key]))) errors.push(`${key} must be an object`);
  }
  const { workflow, apps, settings } = extrasOf(obj);
  if (workflow) {
    for (const key of ['remote', 'issues']) if (workflow[key] !== undefined && workflow[key] !== 'none') errors.push(`workflow.${key} must be "none" (or left out)`);
    const list = workflow.protectedBranches;
    if (list !== undefined) {
      if (!Array.isArray(list)) errors.push('workflow.protectedBranches must be an array of branch names');
      else list.forEach((b, i) => { if (typeof b !== 'string' || !BRANCH_RE.test(b) || b.startsWith('-')) errors.push(`workflow.protectedBranches[${i}] is not a branch name`); });
    }
  }
  if (apps) {
    for (const [key, value] of Object.entries(apps)) {
      // 3.7.1 (D6): the reason for the declaration, as exclude / owned / seed carry one.
      if (key === 'reason') { if (typeof value !== 'string') errors.push('apps.reason must be a string'); continue; }
      if (!['frontend', 'backend'].includes(key)) errors.push(`apps.${key} is unknown (frontend / backend / reason)`);
      else if (!cleanAppDir(value)) errors.push(`apps.${key} must be a relative directory inside the product`);
    }
  }
  if (settings && settings.enabledPlugins !== undefined) {
    const plugins = settings.enabledPlugins;
    if (!plugins || typeof plugins !== 'object' || Array.isArray(plugins) || Object.values(plugins).some((v) => typeof v !== 'boolean')) {
      errors.push('settings.enabledPlugins must map plugin names to true / false');
    }
  }
  return errors;
}

/** `init --config <file>`: the manifest-only keys from a JSON file (an error stops init). */
function readExtrasFile(file) {
  let parsed;
  try { parsed = JSON.parse(fs.readFileSync(file, 'utf8')); } catch (error) { throw new Error(`--config ${file}: ${error.message}`); }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new Error(`--config ${file} must hold a JSON object`);
  const errors = extrasErrors(parsed);
  if (errors.length) throw new Error(`--config ${file}: ${errors.join('; ')}`);
  return extrasOf(parsed);
}

module.exports = {
  extraBranches, denyEntries, addProtectedDenies, codexProtectedRules, writeCodexProtectedRules, appDir, applyEnabledPlugins,
  extrasOf, extrasErrors, readExtrasFile, CODEX_RULES_FILE, EXTRA_KEYS,
};
